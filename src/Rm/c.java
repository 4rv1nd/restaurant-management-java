    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int t,g_total,total=0;
        DefaultTableModel dtm1=(DefaultTableModel)jTable1.getModel();
        DefaultTableModel dtm=(DefaultTableModel)jTable2.getModel();
        if(jTextField2.getText().equals("") | jTextField3.getText().equals("") | jTextField4.getText().equals("")){
           JOptionPane.showMessageDialog(null,"Please Fill All Fields");
        }
        else{
            
        
            int i=jTable1.getSelectedRow();
            String s=String.valueOf(dtm1.getValueAt(i,1));
            int q=Integer.valueOf(jTextField4.getText());
            int p=Integer.valueOf(s);
            total=p*q;
            
            //
          
        t=dtm.getRowCount();
        if(t==0){//if table was empty
            dtm.addRow(new Object[]{jTextField3.getText(),s,jTextField4.getText(),""+total}); //For adding Dish into 2nd Table
        }
        else{
            int r=1;
            t=dtm.getRowCount();    
            for(int j=0;j<=(t-1);j++){
                if(dtm.getValueAt(j,0).equals(jTextField3.getText())){// checking dish is exist or not
                    r=(int)JOptionPane.showConfirmDialog(null,"Dish Already Exist Do you want to replace old dish","ERROR",JOptionPane.ERROR_MESSAGE);
                    if(r==0){
                        dtm.removeRow(t-1);
                        dtm.removeRow(t-2);
                        dtm.setValueAt(jTextField4.getText(),j,2);
                        dtm.setValueAt(total,j,3);
                        break;
                    }
                }
            }
            //if no match found it will add a new row
            if(r==1){
                dtm.removeRow(t-1);
                dtm.removeRow(t-2);
                dtm.addRow(new Object[]{jTextField3.getText(),s,jTextField4.getText(),""+total}); 
            }
        }
        }
        
        //For Calculatio Total amount to insert in table
        t=dtm.getRowCount();
        g_total=0;
        for(int s=0;s<=(t-1);s++){
            if(!dtm.getValueAt(s,3).equals("")){
                g_total+=Integer.valueOf(""+dtm.getValueAt(s,3));
            }
        }
        dtm.addRow(new Object[]{"","","",""}); 
        dtm.addRow(new Object[]{"","","Total",g_total});     
        
        dtm1.setRowCount(0);
        jTextField4.setText("");
        jTextField3.setText("");
        
    }//GEN-LAST:event_jButton3ActionPerformed

