   public void refresh(){
        db_conn d=new db_conn();
        d.query="show tables like 'order%'";
        ResultSet rs=(ResultSet)d.select();
        jComboBox1.removeAllItems();
        try{
            while(rs.next()){
                String ssss="";
                ssss=rs.getString(1);
                jComboBox1.addItem(ssss.substring(6));
            }
        }
        catch(HeadlessException | SQLException e){
            JOptionPane.showMessageDialog(null,""+d.error());
        }
    }
