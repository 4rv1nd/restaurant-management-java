    private void wiKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_wiKeyReleased
    jButton2.setVisible(false);
        db_conn d=new db_conn();
    try
    {
        d.query="select * from waiter where id=?";
        d.a.add(wi.getText());
        ResultSet rs=d.select();
        
        if(rs.next())
        {
            jComboBox1.removeAllItems();
            jComboBox1.addItem(rs.getString("gender"));
            wc.setText(rs.getString("contact"));
            wa.setText(rs.getString("address"));
            wn.setText(rs.getString("name"));
            wp.setText(rs.getString("password"));
       }
        else
        {
            jComboBox1.removeAllItems();
            wc.setText("");
            wa.setText("");
            wn.setText("");
            wp.setText("");
        }
    }
    catch(NullPointerException e){
        JOptionPane.showMessageDialog(null,d.error());
    }
    catch(NumberFormatException | SQLException e){
       System.out.println(e); 
    }
    }//GEN-LAST:event_wiKeyReleased

